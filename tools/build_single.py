# -*- coding: utf-8 -*-
"""把包源码合并成 QMT/PTrade 可复制到策略尾部的单文件。

用法：
    python tools/build_single.py
    python tools/build_single.py --root          # 同时刷新根目录 jingniflow.py
    python tools/build_single.py --check --root  # 只校验，不写文件

产物：
    dist/jingniflow_single.py       UTF-8
    dist/jingniflow_single_gbk.py   GBK（QMT 用）
    dist/build-manifest.json        版本/源码 hash/产物 hash
    jingniflow.py                   （可选）UTF-8 单文件

发布前建议在源码目录执行 ``--check --root``；CI 会先校验已提交根文件，
再构建并校验全部产物。
"""

import argparse
import ast
import hashlib
import io
import json
import os
import re
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKAGE = os.path.join(ROOT, "jingniflow")

MODULES = [
    "version.py",
    "core/errors.py",
    "core/contract.py",
    "core/order.py",
    "core/risk.py",
    "core/config.py",
    "core/runtime.py",
    "core/calendar.py",
    "core/instrument.py",
    "adapters/base.py",
    "adapters/goldminer.py",
    "adapters/qmt.py",
    "adapters/ptrade.py",
    "adapters/__init__.py",
    "api/market.py",
    "api/account.py",
    "api/trade.py",
    "api/risk.py",
    "api/instrument.py",
    "api/calendar.py",
    "api/ipo.py",
    "api/repo.py",
    "api/runtime.py",
    "api/lifecycle.py",
    "api/diagnose.py",
    "compat/legacy.py",
]

HEADER_UTF8 = """# -*- coding: utf-8 -*-
# Generated by tools/build_single.py. DO NOT EDIT.
# JingniFlow single-file distribution, version: {version}
# Source-SHA256: {source_hash}
# Build-UTC: {build_time}
# Copy this file to the tail of a QMT/PTrade strategy, or import it for research.
"""

HEADER_GBK = """# coding: gbk
# Generated by tools/build_single.py. DO NOT EDIT.
# JingniFlow single-file distribution (GBK), version: {version}
# Source-SHA256: {source_hash}
# Build-UTC: {build_time}
# Copy this file to the tail of a QMT strategy.
"""

MANIFEST_NAME = "build-manifest.json"
DIST_DIR = os.path.join(ROOT, "dist")
UTF8_PATH = os.path.join(DIST_DIR, "jingniflow_single.py")
GBK_PATH = os.path.join(DIST_DIR, "jingniflow_single_gbk.py")
ROOT_PATH = os.path.join(ROOT, "jingniflow.py")
MANIFEST_PATH = os.path.join(DIST_DIR, MANIFEST_NAME)

INTERNAL_IMPORT = re.compile(r"^\s*(from\s+\.+|from\s+jingniflow|import\s+jingniflow)")


def read_version():
    path = os.path.join(PACKAGE, "version.py")
    with io.open(path, "r", encoding="utf-8") as handle:
        content = handle.read()
    match = re.search(r"__version__\s*=\s*['\"]([^'\"]+)['\"]", content)
    return match.group(1) if match else "0.0.0"


def read_all():
    path = os.path.join(PACKAGE, "compat", "legacy.py")
    with io.open(path, "r", encoding="utf-8") as handle:
        content = handle.read()
    match = re.search(r"__all__\s*=\s*(\[[\s\S]*?\])", content)
    if not match:
        raise SystemExit("cannot find __all__ in compat/legacy.py")
    try:
        exports = list(ast.literal_eval(match.group(1)))
    except Exception as exc:
        raise SystemExit("invalid __all__ in compat/legacy.py: {0}".format(exc))
    if not exports:
        raise SystemExit("__all__ in compat/legacy.py is empty")
    return exports


def strip_module(path):
    with io.open(path, "r", encoding="utf-8") as handle:
        lines = handle.readlines()
    output = []
    skipping_main = False
    skipping_import = False
    for line in lines:
        if skipping_import:
            if ")" in line:
                skipping_import = False
            continue
        if re.match(r"^if\s+__name__\s*==\s*['\"]__main__['\"]\s*:", line):
            skipping_main = True
            continue
        if skipping_main:
            if line.startswith("if "):
                skipping_main = False
            else:
                continue
        if INTERNAL_IMPORT.match(line):
            if "(" in line and ")" not in line:
                skipping_import = True
            continue
        output.append(line)
    return "".join(output).strip() + "\n"


def build_text():
    chunks = []
    for relative in MODULES:
        path = os.path.join(PACKAGE, relative.replace("/", os.sep))
        if not os.path.exists(path):
            raise SystemExit("missing module: {0}".format(path))
        chunks.append("\n# ---- {0} ----\n".format(relative))
        chunks.append(strip_module(path))
    exports = read_all()
    export_block = "\n__all__ = {0}\n".format(repr(exports))
    return "".join(chunks) + export_block


def source_hash():
    digest = hashlib.sha256()
    for relative in MODULES:
        path = os.path.join(PACKAGE, relative.replace("/", os.sep))
        if not os.path.exists(path):
            raise SystemExit("missing module: {0}".format(path))
        with io.open(path, "rb") as handle:
            data = handle.read()
        digest.update(relative.encode("utf-8"))
        digest.update(b"\0")
        digest.update(data.replace(b"\r\n", b"\n"))
        digest.update(b"\0")
    return digest.hexdigest()


def build_time():
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    if epoch:
        try:
            return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(int(epoch)))
        except (TypeError, ValueError):
            pass
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def render(version, digest, timestamp, encoding):
    body = build_text()
    template = HEADER_GBK if encoding == "gbk" else HEADER_UTF8
    header = template.format(
        version=version, source_hash=digest, build_time=timestamp
    )
    return header + "\n" + body


def read_text(path, encoding):
    with io.open(path, "r", encoding=encoding) as handle:
        return handle.read()


def artifact_hash(path):
    with io.open(path, "rb") as handle:
        data = handle.read()
    return hashlib.sha256(data).hexdigest(), len(data)


def header_build_time(path, encoding):
    text = read_text(path, encoding)
    for line in text.splitlines()[:8]:
        if line.startswith("# Build-UTC:"):
            return line.split(":", 1)[1].strip()
    return None


def check_file(path, text, encoding, label):
    if not os.path.exists(path):
        print("[STALE] missing {0}: {1}".format(label, path))
        return False
    expected_bytes = text.encode(encoding)
    with io.open(path, "rb") as handle:
        actual = handle.read()
    if actual != expected_bytes:
        print("[STALE] {0}: {1}".format(label, path))
        return False
    print("[OK] {0}: {1}".format(label, path))
    return True


def check_manifest(version, digest, paths, allow_missing=False):
    if not os.path.exists(MANIFEST_PATH):
        if allow_missing:
            print("[SKIP] missing manifest: {0}".format(MANIFEST_PATH))
            return True
        print("[STALE] missing manifest: {0}".format(MANIFEST_PATH))
        return False
    with io.open(MANIFEST_PATH, "r", encoding="utf-8") as handle:
        try:
            manifest = json.load(handle)
        except ValueError as exc:
            print("[STALE] invalid manifest: {0}".format(exc))
            return False
    if manifest.get("version") != version:
        print("[STALE] manifest version: {0}".format(manifest.get("version")))
        return False
    if manifest.get("source_sha256") != digest:
        print("[STALE] manifest source hash")
        return False
    entries = manifest.get("artifacts") or {}
    ok = True
    for path in paths:
        relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
        expected = entries.get(relative)
        if not expected:
            print("[STALE] manifest missing artifact: {0}".format(relative))
            ok = False
            continue
        checksum, size = artifact_hash(path)
        if expected.get("sha256") != checksum or expected.get("bytes") != size:
            print("[STALE] manifest hash: {0}".format(relative))
            ok = False
        else:
            print("[OK] manifest: {0}".format(relative))
    return ok


def write_manifest(version, digest, timestamp, paths):
    entries = {}
    for path in paths:
        relative = os.path.relpath(path, ROOT).replace(os.sep, "/")
        checksum, size = artifact_hash(path)
        entries[relative] = {"sha256": checksum, "bytes": size}
    manifest = {
        "version": version,
        "source_sha256": digest,
        "generated_at": timestamp,
        "artifacts": entries,
    }
    with io.open(MANIFEST_PATH, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True))
        handle.write("\n")
    print("wrote {0}".format(MANIFEST_PATH))


def run_check(version, digest, include_root, allow_missing=False):
    targets = [
        (UTF8_PATH, "utf-8", "dist"),
        (GBK_PATH, "gbk", "dist"),
    ]
    if include_root:
        targets.append((ROOT_PATH, "utf-8", "root"))
    ok = True
    checked_paths = []
    for path, encoding, label in targets:
        if not os.path.exists(path):
            if allow_missing:
                print("[SKIP] missing {0}: {1}".format(label, path))
                continue
            print("[STALE] missing {0}: {1}".format(label, path))
            ok = False
            continue
        timestamp = header_build_time(path, encoding)
        if timestamp is None:
            print("[STALE] cannot read build timestamp: {0}".format(path))
            ok = False
            continue
        if not check_file(path, render(version, digest, timestamp, encoding), encoding, label):
            ok = False
        checked_paths.append(path)
    if checked_paths:
        if not check_manifest(version, digest, checked_paths, allow_missing):
            ok = False
    elif not allow_missing:
        ok = False
    print("[CHECK] {0}".format("OK" if ok else "FAILED"))
    return 0 if ok else 1


def write_text(path, text, encoding):
    directory = os.path.dirname(path)
    if directory and not os.path.isdir(directory):
        os.makedirs(directory)
    with io.open(path, "w", encoding=encoding, newline="\n") as handle:
        handle.write(text)
    print("wrote {0} ({1})".format(path, encoding))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", action="store_true", help="also refresh root jingniflow.py")
    parser.add_argument("--check", action="store_true", help="verify artifacts without writing")
    parser.add_argument(
        "--allow-missing",
        action="store_true",
        help="with --check, skip missing files (used for a root-only drift gate)",
    )
    args = parser.parse_args()
    version = read_version()
    digest = source_hash()
    timestamp = build_time()
    if args.check:
        return run_check(version, digest, args.root, args.allow_missing)

    utf8_text = render(version, digest, timestamp, "utf-8")
    gbk_text = render(version, digest, timestamp, "gbk")
    write_text(UTF8_PATH, utf8_text, "utf-8")
    write_text(GBK_PATH, gbk_text, "gbk")
    paths = [UTF8_PATH, GBK_PATH]
    if args.root:
        write_text(ROOT_PATH, utf8_text, "utf-8")
        paths.append(ROOT_PATH)
    write_manifest(version, digest, timestamp, paths)
    return 0


if __name__ == "__main__":
    sys.exit(main())
